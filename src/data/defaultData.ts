// Helper to calculate the next Saturday and upcoming Saturdays
export function getUpcomingSaturdays(count = 4): string[] {
  const dates: string[] = [];
  const today = new Date();
  
  // Find next Saturday (day 6)
  const currentDay = today.getDay();
  let daysUntilSaturday = (6 - currentDay + 7) % 7;
  if (daysUntilSaturday === 0) {
    // If today is Saturday, next Saturday is in 7 days or today if early
    daysUntilSaturday = 0; // Show current Saturday
  }
  
  const nextSaturday = new Date(today);
  nextSaturday.setDate(today.getDate() + daysUntilSaturday);
  
  for (let i = 0; i < count; i++) {
    const d = new Date(nextSaturday);
    d.setDate(nextSaturday.getDate() + i * 7);
    const yyyy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    dates.push(`${yyyy}-${mm}-${dd}`);
  }
  
  return dates;
}

